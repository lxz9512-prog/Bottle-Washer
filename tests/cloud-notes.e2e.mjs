import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { setWorkspacePanel } from './workspace-controls.mjs';

const base = process.env.APP_URL ?? 'http://127.0.0.1:5185/';
const password = (await readFile(process.env.NOTES_PASSWORD_FILE ?? '.local/editing-password.txt', 'utf8')).trim();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1512, height: 1100 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}#/demo`);
  await page.locator('[data-device-frame]').waitFor();
  await setWorkspacePanel(page, '交互说明', true);
  const panel = page.locator('.info-panel');
  await panel.getByRole('button', { name: '编辑', exact: true }).click();
  await page.getByLabel('编辑密码', { exact: true }).fill('wrong-password-for-e2e');
  await panel.getByRole('button', { name: '解锁编辑', exact: true }).click();
  await panel.getByRole('alert').filter({ hasText: '编辑密码不正确' }).waitFor();
  await page.getByLabel('编辑密码', { exact: true }).fill(password);
  await panel.getByRole('button', { name: '解锁编辑', exact: true }).click();
  const body = panel.getByRole('textbox', { name: '说明 1 正文', exact: true });
  await body.waitFor();
  const original = await body.inputValue();
  await body.fill(`${original}\n待保存草稿`);
  await setWorkspacePanel(page, '交互说明', false);
  await setWorkspacePanel(page, '交互说明', true);
  assert.equal(await body.inputValue(), `${original}\n待保存草稿`);
  await panel.getByRole('button', { name: '取消', exact: true }).click();
  await panel.getByRole('button', { name: '编辑', exact: true }).click();
  assert.equal(await body.inputValue(), original, 'cancel restores cloud contents');
  await body.fill(`${original} `);
  const saveResponse = page.waitForResponse(response => response.url().endsWith('/api/notes/pages/devices') && response.request().method() === 'PUT');
  await panel.getByRole('button', { name: '保存到线上', exact: true }).click();
  const savedResponse = await saveResponse;
  assert.equal(savedResponse.status(), 200);
  const saved = await savedResponse.json();
  assert.equal(saved.notes[0].body, original);
  await panel.getByRole('status').filter({ hasText: '已保存到线上' }).waitFor();
  const independent = await browser.newContext();
  const publicRead = await independent.request.get(`${base}api/notes/pages/devices`);
  assert.deepEqual(await publicRead.json(), saved, 'separate visitor sees persisted contents');
  const stale = await context.request.put(`${base}api/notes/pages/devices`, { data: { notes: saved.notes, revision: 'stale-test-revision' } });
  assert.equal(stale.status(), 409);
  await page.reload();
  await setWorkspacePanel(page, '交互说明', true);
  await panel.getByRole('button', { name: '编辑', exact: true }).click();
  await body.waitFor();
  assert.equal(await body.inputValue(), original, 'refresh reads cloud contents and keeps session');
  await panel.getByRole('button', { name: '取消', exact: true }).click();
  await panel.getByRole('button', { name: '锁定编辑', exact: true }).click();
  await panel.getByRole('status').filter({ hasText: '编辑已锁定' }).waitFor();
  assert.equal((await (await context.request.get(`${base}api/notes/session`)).json()).unlocked, false);
  const unauthorized = await context.request.put(`${base}api/notes/pages/devices`, { data: saved });
  assert.equal(unauthorized.status(), 401);
  await mkdir('tests/artifacts/cloudflare', { recursive: true });
  await page.screenshot({ path: 'tests/artifacts/cloudflare/desktop-notes.png' });
  assert.deepEqual(errors, []);
  await independent.close();
  console.log('PASS: password unlock, draft preservation, cancel, online save, independent public read, conflict protection, session refresh and lock. Existing note contents preserved.');
} finally { await browser.close(); }
